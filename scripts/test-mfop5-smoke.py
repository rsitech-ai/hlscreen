#!/usr/bin/env python3
"""Parser/failure tests with real Python children; not a native source oracle.

The committed portable fixture itself is generated by the Rust owner test.
These temporary, deliberately minimal inputs test the verifier's failure paths.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

SPEC = importlib.util.spec_from_file_location(
    "mfop5_smoke", Path(__file__).with_name("verify-mfop5-smoke.py")
)
assert SPEC and SPEC.loader
SMOKE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(SMOKE)


class SmokeTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.fixture = self.root / "fixture"
        (self.fixture / "feed").mkdir(parents=True)
        (self.fixture / "README.md").write_text("Verifier unit input only.\n")
        (self.fixture / "feed/events.mfsf").write_bytes(b"MFOP1\0\0\0" + b"a" * 40)
        (self.fixture / "feed/committed.json").write_text("{}")
        self.summary = {
            "cursor": {"feed_id": "a" * 40, "sequence": 3, "offset": 48},
            "source_cursor": {"feed_id": "b" * 40, "sequence": 9, "offset": 64},
            "events": {"trade": 2},
            "data_gaps": 0,
            "sealed": True,
            "as_of_ms": 1,
            "availability_time_ns": None,
            "clock_policy": "max_checked_owner_approximation_physical_order_v1",
            "instruments": [],
            "float_projection": "features_and_display_only",
        }
        self.manifest = {
            "schema_version": 1,
            "synthetic": True,
            "source_profile": 5,
            "owner_history_schema": 4,
            "portable_native_authentication": False,
            "expected_summary": self.summary,
            "expected_market_events": 2,
            "files": [
                {
                    "path": name,
                    "bytes": (self.fixture / name).stat().st_size,
                    "sha256": hashlib.sha256(
                        (self.fixture / name).read_bytes()
                    ).hexdigest(),
                }
                for name in sorted(SMOKE.REQUIRED_FILES)
            ],
        }
        self.save_manifest()

    def save_manifest(self):
        (self.fixture / "manifest.json").write_text(json.dumps(self.manifest))

    def output(self, summary=None):
        summary = self.summary if summary is None else summary
        return (
            "shared_feed_cursor="
            + json.dumps(summary["cursor"])
            + "\n"
            + "market_events=2\nshared_feed_summary="
            + json.dumps(summary)
            + "\n"
        )

    def child_runner(self, output):
        # Run real subprocess byte/UTF8 decoding and exit handling. Injection
        # replaces only the command for unit tests; native smokes run actual hls.
        return lambda _argv: SMOKE.run_child(
            [sys.executable, "-c", f"import os; os.write(1,{output.encode()!r})"]
        )

    def verify(self, runner=None):
        return SMOKE.verify(
            Path(sys.executable),
            self.fixture,
            self.root / "new-data",
            runner or self.child_runner(self.output()),
        )

    def test_valid_child_reports_pair_and_unchanged_fixture(self):
        result = self.verify()
        self.assertEqual(result["summary"], self.summary)
        self.assertTrue(result["fixture_bytes_and_metadata_unchanged"])
        self.assertFalse(result["native_source_authentication_on_this_platform"])

    def test_corrupt_fixture_is_rejected_before_child(self):
        (self.fixture / "feed/events.mfsf").write_bytes(b"corrupt")
        with self.assertRaisesRegex(ValueError, "hash/length"):
            self.verify(lambda _argv: self.fail("child must not run"))

    def test_existing_data_directory_is_refused(self):
        (self.root / "new-data").mkdir()
        with self.assertRaisesRegex(ValueError, "must be new"):
            self.verify()

    def test_wrong_summary_fields_remain_failed(self):
        for name, wrong in [
            ("source_cursor", {}),
            ("cursor", {}),
            ("events", {"trade": 3}),
            ("sealed", False),
            ("availability_time_ns", 1),
            ("as_of_ms", 2),
        ]:
            with self.subTest(name=name):
                summary = dict(self.summary, **{name: wrong})
                with self.assertRaises(ValueError):
                    self.verify(self.child_runner(self.output(summary)))

    def test_numeric_type_forgery_and_nonfinite_are_rejected(self):
        for name, value in [
            ("data_gaps", 0.0),
            ("sealed", 1),
            ("as_of_ms", 1.0),
            ("events", {"trade": 2.0}),
            ("events", {"trade": True}),
        ]:
            with self.subTest(name=name, value=value), self.assertRaises(ValueError):
                self.verify(
                    self.child_runner(self.output(dict(self.summary, **{name: value})))
                )
        for field in [
            "schema_version",
            "source_profile",
            "owner_history_schema",
            "expected_market_events",
        ]:
            original = self.manifest[field]
            self.manifest[field] = float(original)
            self.save_manifest()
            with self.assertRaises(ValueError):
                self.verify()
            self.manifest[field] = original
        self.save_manifest()
        for value in ["NaN", "Infinity", "-Infinity", "1e400", "-1e400"]:
            with self.assertRaisesRegex(ValueError, "nonfinite"):
                SMOKE.parse_json(value)

    def test_child_output_is_capped_during_capture(self):
        with self.assertRaisesRegex(ValueError, "output bound"):
            SMOKE.run_child(
                [sys.executable, "-c", "import os; os.write(1,b'x'*1048577)"]
            )

    def test_missing_duplicate_or_nonjson_summary_is_rejected(self):
        for output in [
            "market_events=2\n",
            self.output() + self.output(),
            "shared_feed_summary=not-json\n",
        ]:
            with self.assertRaises(ValueError):
                self.verify(self.child_runner(output))

    def test_duplicate_manifest_key_and_path_are_rejected(self):
        path = self.fixture / "manifest.json"
        path.write_text('{"schema_version":1,"schema_version":1}')
        with self.assertRaisesRegex(ValueError, "duplicate JSON"):
            self.verify()
        self.manifest["files"][1] = self.manifest["files"][0]
        self.save_manifest()
        with self.assertRaisesRegex(ValueError, "duplicate fixture"):
            self.verify()

    def test_actual_nonzero_utf8_and_timeout_are_not_success(self):
        commands = [
            ([sys.executable, "-c", "import sys; sys.exit(7)"], ValueError),
            (
                [sys.executable, "-c", "import os; os.write(1,b'\\xff')"],
                UnicodeDecodeError,
            ),
            (
                [sys.executable, "-c", "import time; time.sleep(2)"],
                subprocess.TimeoutExpired,
            ),
        ]
        for argv, kind in commands:
            with self.subTest(argv=argv), self.assertRaises(kind):
                SMOKE.run_child(argv, timeout=0.1)

    def test_fixture_mutation_during_child_is_rejected(self):
        def mutate(argv):
            result = self.child_runner(self.output())(argv)
            (self.fixture / "README.md").write_text("changed")
            return result

        with self.assertRaisesRegex(ValueError, "changed during"):
            self.verify(mutate)


if __name__ == "__main__":
    unittest.main()
